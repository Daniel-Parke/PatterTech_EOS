#!/usr/bin/env python3
"""Write the component inventory from what is actually in the tree.

Starts at `requirements.txt`, follows `Requires-Dist` through the
metadata unpacked in `vendor/`, and adds one entry for every directory
under `third_party/`. Reports what each component says about itself and
nothing more: a component with no licence file gets `NOASSERTION`, and
deciding what to do about that is a person's job.

    python scripts/licence_scan.py            write sbom/inventory.json
    python scripts/licence_scan.py --check    fail if the file is stale
    python scripts/licence_scan.py --out FILE write somewhere else
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "sbom" / "inventory.json"
NOTE = ("Generated by scripts/licence_scan.py. Do not edit by hand: "
        "run the scan.")

REQUIREMENT = re.compile(r"^([A-Za-z0-9._-]+)\s*==\s*([^\s;#]+)")
REQUIRES_DIST = re.compile(r"^Requires-Dist:\s*([A-Za-z0-9._-]+)", re.M)
LICENCE_FIELD = re.compile(r"^License(?:-Expression)?:\s*(.+)$", re.M)
SPDX_IN_FILE = re.compile(r"SPDX-License-Identifier:\s*([^\s*/#]+)")
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING)(\..*)?$", re.I)

UNKNOWN = "NOASSERTION"


def normalise(name):
    return re.sub(r"[-_.]+", "-", (name or "").strip()).lower()


def requirements(root):
    """(name, version) for every pinned line in requirements.txt."""
    path = root / "requirements.txt"
    out = []
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = REQUIREMENT.match(line)
        if match:
            out.append((match.group(1), match.group(2)))
        else:
            out.append((re.split(r"[<>=!~\[; ]", line, 1)[0], ""))
    return out


def metadata_for(root, name):
    """The METADATA file for one distribution, or None."""
    vendor = root / "vendor"
    if not vendor.is_dir():
        return None
    wanted = normalise(name)
    for path in sorted(vendor.glob("*.dist-info/METADATA")):
        stem = path.parent.name[: -len(".dist-info")]
        if normalise(stem.rsplit("-", 1)[0]) == wanted:
            return path
    return None


def read_metadata(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    licence = ""
    match = LICENCE_FIELD.search(text)
    if match:
        licence = match.group(1).strip()
    version = ""
    version_match = re.search(r"^Version:\s*(.+)$", text, re.M)
    if version_match:
        version = version_match.group(1).strip()
    requires = [m for m in REQUIRES_DIST.findall(text)]
    return licence, version, requires


def from_manifests(root):
    """Every pinned requirement and everything it drags in with it."""
    found = {}
    queue = [(name, version) for name, version in requirements(root)]
    seen = set()
    while queue:
        name, version = queue.pop(0)
        key = normalise(name)
        if key in seen:
            continue
        seen.add(key)
        path = metadata_for(root, name)
        if path is None:
            found[key] = {
                "name": key, "version": version or "unknown",
                "source": "requirements.txt", "licence": UNKNOWN,
            }
            continue
        licence, declared, requires = read_metadata(path)
        found[key] = {
            "name": key,
            "version": version or declared or "unknown",
            "source": path.relative_to(root).as_posix(),
            "licence": licence or UNKNOWN,
        }
        for other in requires:
            if normalise(other) not in seen:
                queue.append((other, ""))
    return found


def from_third_party(root):
    """One entry per vendored directory, licence file or not."""
    found = {}
    base = root / "third_party"
    if not base.is_dir():
        return found
    for path in sorted(p for p in base.iterdir() if p.is_dir()):
        licence = UNKNOWN
        for candidate in sorted(path.iterdir()):
            if candidate.is_file() and LICENCE_FILE.match(candidate.name):
                text = candidate.read_text(encoding="utf-8", errors="replace")
                match = SPDX_IN_FILE.search(text)
                licence = match.group(1) if match else UNKNOWN
                break
        found[normalise(path.name)] = {
            "name": normalise(path.name),
            "version": "unknown",
            "source": path.relative_to(root).as_posix(),
            "licence": licence,
        }
    return found


def inventory(root):
    components = from_manifests(root)
    components.update(from_third_party(root))
    return {
        "note": NOTE,
        "components": [components[k] for k in sorted(components)],
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--check", action="store_true",
                        help="compare with the committed file, do not write")
    args = parser.parse_args(argv)

    doc = inventory(ROOT)
    text = json.dumps(doc, indent=1) + "\n"
    out = Path(args.out)

    if args.check:
        current = out.read_text(encoding="utf-8") if out.is_file() else ""
        if current == text:
            print("%s is current: %d components"
                  % (out.name, len(doc["components"])))
            return 0
        print("%s is stale, run scripts/licence_scan.py" % out.name,
              file=sys.stderr)
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print("wrote %s: %d components" % (out, len(doc["components"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
